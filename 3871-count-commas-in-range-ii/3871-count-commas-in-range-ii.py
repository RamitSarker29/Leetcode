class Solution:
    def countCommas(self, n: int) -> int:
        if n // 1000 == 0 :
            return 0
        
        if n // 1000 >= 1 and n // 1000000 >= 1 and n // 1000000000 >= 1 and n // 1000000000000 >= 1 and n // 1000000000000000 >= 1 :
            
            return (n - 1000 + 1) + (n - 1000000 + 1) + (n - 1000000000 + 1) + (n - 1000000000000 + 1) + (n - 1000000000000000 + 1)
        
        
        if n // 1000 >= 1 and n // 1000000 >= 1 and n // 1000000000 >= 1 and n // 1000000000000 >= 1:
            
            return (n - 1000 + 1) + (n - 1000000 + 1) + (n - 1000000000 + 1) + (n - 1000000000000 + 1)
        
        
        if n // 1000 >= 1 and n // 1000000 >= 1 and n // 1000000000 >= 1:
            
            return (n - 1000 + 1) + (n - 1000000 + 1) + (n - 1000000000 + 1)
        
        
        if n // 1000 >= 1 and n // 1000000 >= 1 :
            
            return (n - 1000 + 1) + (n - 1000000 + 1)
        if n // 1000 >= 1 :
            return n - 1000 + 1
        